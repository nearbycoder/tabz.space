import { Download } from "lucide-react";
import { useMemo, useState } from "react";
import { renderSVG } from "uqr";
import type { WidgetProps } from "../kit";

type Data = { text: string };

export default function QrCode({ data, save, readOnly }: WidgetProps<Data>) {
	const [text, setText] = useState(data.text);
	// uqr draws only squares from the encoded bits; the text never ends up in the markup.
	const svg = useMemo(
		() => (text ? renderSVG(text.slice(0, 1000), { border: 2 }) : ""),
		[text],
	);
	const download = () => {
		const link = document.createElement("a");
		link.href = URL.createObjectURL(new Blob([svg], { type: "image/svg+xml" }));
		link.download = "qr-code.svg";
		link.click();
		URL.revokeObjectURL(link.href);
	};
	return (
		<div className="space-y-2">
			{svg && (
				<div
					className="mx-auto aspect-square w-40 overflow-hidden rounded-xl bg-white [&>svg]:size-full"
					// biome-ignore lint/security/noDangerouslySetInnerHtml: generated by uqr, contains no user text
					dangerouslySetInnerHTML={{ __html: svg }}
				/>
			)}
			<div className="flex gap-1.5">
				<input
					className="field"
					value={text}
					onChange={(event) => {
						setText(event.target.value);
						if (!readOnly) save({ text: event.target.value });
					}}
					placeholder="Text or link"
					maxLength={1000}
					aria-label="QR code content"
				/>
				<button
					type="button"
					className="icon-btn shrink-0"
					aria-label="Download SVG"
					onClick={download}
					disabled={!svg}
				>
					<Download className="size-4" />
				</button>
			</div>
		</div>
	);
}
